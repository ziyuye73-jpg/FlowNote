const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const { _electron: electron } = require('playwright');
test('Electron opens isolated desktop UI and exposes only named operations', async () => {
  const profile = await require('node:fs/promises').mkdtemp(path.join(require('node:os').tmpdir(),'flownote-ui-profile-'));
  const app = await electron.launch({ args:[path.resolve(__dirname,'..'),'--user-data-dir='+profile], env:{...process.env,ELECTRON_RUN_AS_NODE:''} });
  let mainError='';
  app.process().stderr.on('data',data=>{mainError+=data.toString();});
  await app.evaluate(({dialog})=>{dialog.showErrorBox=()=>{};});
  try {
    const page = await app.firstWindow();
    await page.locator('#environment').filter({hasText:'Python'}).waitFor();
    assert.equal(await page.title(),'FlowNote · 流程笔记');
    const state = await page.evaluate(() => ({ node:typeof require, api:Object.keys(window.flowNote), csp:document.querySelector('meta[http-equiv="Content-Security-Policy"]').content }));
    assert.equal(state.node,'undefined'); assert(state.api.includes('importRecording')); assert(!state.api.includes('send'));
    assert(state.csp.includes("connect-src 'none'"));
    assert.equal(await page.locator('#export').isDisabled(),true);
    assert.equal(await page.locator('#description').count(),0);
    assert.equal(await page.locator('#post-title').count(),0);
    assert.equal(await page.locator('#topics').count(),0);
    await page.locator('[data-tab="settings"]').click();
    await page.waitForFunction(()=>document.getElementById('model-url').value.length>0);
    assert.equal(await page.locator('#fetch-models').isVisible(),true);
    assert.equal(await page.locator('#test-model').isVisible(),true);
    await page.locator('[data-tab="workbench"]').click();
    assert.equal(await page.locator('#resume-fill').isVisible(),true);
    await page.waitForFunction(()=>document.getElementById('project-select').value==='douyin-video');
    assert.equal(await page.locator('#automation-title').textContent(),'抖音视频发布');
    await page.locator('#run').click();
    assert.match(await page.locator('#notice').textContent(),/选择支持的流程 JSON/);
    const temp = await require('node:fs/promises').mkdtemp(path.join(require('node:os').tmpdir(),'flownote-ui-'));
    const source = path.join(temp,'sample.json');
    await require('node:fs/promises').writeFile(source,JSON.stringify({producer:'windows-record-replay',schemaVersion:3,title:'界面导入测试',steps:[{id:3,action:'fill',url:'https://example.test/',target:{label:'日期'},value:'2026-11-13'}]}));
    await app.evaluate(({dialog},file) => { dialog.showOpenDialog = async () => ({canceled:false,filePaths:[file]}); },source);
    await page.locator('[data-tab="files"]').click();
    await page.locator('#import').click();
    await page.locator('#flow-title').filter({visible:true}).waitFor();
    assert.equal(await page.locator('#flow-title').inputValue(),'界面导入测试');
    await page.locator('#flow-title').fill('编辑后流程');
    await page.locator('#save').click();
    await page.locator('#notice').filter({hasText:'编辑已应用'}).waitFor();
    await app.evaluate(({dialog},folder) => { dialog.showOpenDialog = async () => ({canceled:false,filePaths:[folder]}); },temp);
    await page.locator('[data-tab="editor"]').click();
    await page.locator('#export').click();
    await page.locator('#notice').filter({hasText:'Skill 草稿已生成'}).waitFor();
    const workflow = JSON.parse(await require('node:fs/promises').readFile(path.join(temp,'recorded-workflow/references/workflow.json'),'utf8'));
    assert.equal(workflow.title,'编辑后流程');assert.equal(workflow.steps[0].id,3);
    await page.locator('[data-tab="files"]').click();
    await page.locator('#library-search').fill('编辑后流程');
    assert.equal(await page.locator('.library-row').count(),1);
    await page.locator('.library-row').getByRole('button',{name:'打开',exact:true}).click();
    await page.locator('#notice').filter({hasText:'已打开：编辑后流程'}).waitFor();
    assert.equal(await page.locator('#flow-title').inputValue(),'编辑后流程');
    await page.locator('[data-tab="workbench"]').click();
    assert.equal(await page.locator('#stat-steps').textContent(),'1');
    await page.waitForFunction(()=>document.getElementById('flow-select').options.length>1);
    const selectedId=await page.locator('#flow-select option').nth(1).getAttribute('value');
    await page.locator('#flow-select').selectOption(selectedId);
    await page.locator('#flow-details').filter({hasText:'当前执行器不支持'}).waitFor();
    assert.match(await page.locator('#flow-details').textContent(),/非逐条回放/);
    await page.locator('#clear-log').click();
    assert.equal(await page.locator('#stat-logs').textContent(),'0');
    await page.locator('[data-tab="files"]').click();
    await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:0});});
    await page.locator('.library-row').getByRole('button',{name:'删除文件',exact:true}).click();
    assert.equal(await page.locator('.library-row').count(),1);
    await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:1});});
    await page.locator('.library-row').getByRole('button',{name:'删除文件',exact:true}).click();
    await page.waitForFunction(()=>document.getElementById('notice').textContent.includes('已移到系统废纸篓') || document.getElementById('notice').classList.contains('error'));
    assert.match(await page.locator('#notice').textContent(),/已移到系统废纸篓/);
    assert.equal(await page.locator('.library-row').count(),0);
    await page.locator('[data-tab="workbench"]').click();
    assert.equal(await page.locator('#flow-select').inputValue(),'');
    await page.screenshot({path:path.resolve(__dirname,'../dist/desktop-preview.png'),fullPage:true});
    const prefs = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences());
    assert.equal(prefs.contextIsolation,true);assert.equal(prefs.nodeIntegration,false);assert.equal(prefs.sandbox,true);
  } finally { await app.close(); }
  assert(!/ReferenceError|Uncaught Exception|Error in before-quit/.test(mainError),mainError);
});
